"""Turn a file into a C byte array header:  embed.py in-file [symbol] > out.h

The array is `unsigned char <symbol>[]` (default web_page) with a trailing
NUL, and `<symbol>_len` holds the size without it."""
import sys

data = open(sys.argv[1], "rb").read()
name = sys.argv[2] if len(sys.argv) > 2 else "web_page"
print("/* generated by tools/embed.py - do not edit */")
print("static const unsigned char %s[] = {" % name)
for i in range(0, len(data), 16):
    print("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
print("    0x00")
print("};")
print("static const unsigned %s_len = %d;" % (name, len(data)))
